#Requires -Version 5.1
<#
.SYNOPSIS
  Register the FR #4463 daily parts-import Scheduled Task on walrus.

.DESCRIPTION
  Creates/updates task "a-search-daily-import" to run daily at 04:00
  Europe/London (local clock). MultipleInstances = IgnoreNew.
  FR #4520: passes MSSQL connection/auth the same way Register-WalrusSqlDrainService
  (#4515) does — env for the launcher, password only from a file (never echoed).

  Lock file: %ProgramData%\a-search\import.lock
#>
[CmdletBinding(SupportsShouldProcess = $true)]
param(
  [string]$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path,
  [string]$NodeExe = 'node',
  [string]$TaskName = 'a-search-daily-import',
  [string]$DailyAt = '04:00',
  [string]$RunAsUser = '',
  [string]$MssqlServer,
  [string]$MssqlDatabase = 'a_search_sandbox',
  [string]$MssqlUser = '',
  [string]$MssqlPasswordFile = '',
  [switch]$MssqlTrustedConnection,
  [string]$AAffiliatesRoot = 'D:\s3\a-affiliates',
  [string]$AMerchantsRoot = 'D:\s3\a-merchants',
  [switch]$Unregister
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$cli = Join-Path $RepoRoot 'walrus\import\cli.js'
if (-not (Test-Path -LiteralPath $cli)) {
  throw "cli.js not found at $cli"
}

if ($Unregister) {
  if ($PSCmdlet.ShouldProcess($TaskName, 'Unregister-ScheduledTask')) {
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction SilentlyContinue
  }
  Write-Host "Unregistered $TaskName"
  return
}

$dataDir = Join-Path $env:ProgramData 'a-search'
if ($PSCmdlet.ShouldProcess($dataDir, 'Ensure data directory')) {
  New-Item -ItemType Directory -Force -Path $dataDir | Out-Null
}
$log = Join-Path $dataDir 'daily-import.log'
$lock = Join-Path $dataDir 'import.lock'
$launcher = Join-Path $dataDir 'run-daily-import.ps1'

$dbNorm = $MssqlDatabase.Trim().ToLowerInvariant()
if ($dbNorm -eq 'madeiradb') {
  throw 'madeiradb_read_only: MSSQL_DATABASE must be a_search or a_search_sandbox'
}
if ($dbNorm -ne 'a_search' -and $dbNorm -ne 'a_search_sandbox') {
  throw "MSSQL_DATABASE_invalid: expected a_search or a_search_sandbox, got $MssqlDatabase"
}

if (-not $MssqlServer) {
  throw 'MssqlServer_required: pass -MssqlServer (e.g. walrus\ASEARCH) like Register-WalrusSqlDrainService'
}

$useTrusted = [bool]$MssqlTrustedConnection
if (-not $useTrusted) {
  if (-not $MssqlUser) {
    throw 'MssqlUser_required: pass -MssqlUser and -MssqlPasswordFile, or -MssqlTrustedConnection'
  }
  if (-not $MssqlPasswordFile) {
    throw 'MssqlPasswordFile_required: pass -MssqlPasswordFile (password never on the command line)'
  }
  if (-not (Test-Path -LiteralPath $MssqlPasswordFile)) {
    throw "secret_file_missing: $MssqlPasswordFile"
  }
}

# Launcher sets MSSQL_* from params / password file then runs cli (FR #4520 / #4515 pattern).
$launcherBody = @"
#Requires -Version 5.1
# Auto-generated by Register-DailyImportTask.ps1 — do not commit secrets.
Set-StrictMode -Version Latest
`$ErrorActionPreference = 'Stop'
`$env:MSSQL_SERVER = '$($MssqlServer -replace "'","''")'
`$env:MSSQL_DATABASE = '$($MssqlDatabase -replace "'","''")'
`$env:A_AFFILIATES_ROOT = '$($AAffiliatesRoot -replace "'","''")'
`$env:A_MERCHANTS_ROOT = '$($AMerchantsRoot -replace "'","''")'
`$env:A_SEARCH_IMPORT_LOCK = '$($lock -replace "'","''")'
"@
if ($useTrusted) {
  $launcherBody += "`n`$env:MSSQL_TRUSTED_CONNECTION = 'true'`n"
} else {
  $launcherBody += @"

`$env:MSSQL_USER = '$($MssqlUser -replace "'","''")'
`$pwFile = '$($MssqlPasswordFile -replace "'","''")'
`$env:MSSQL_PASSWORD = ([System.IO.File]::ReadAllText(`$pwFile)).Trim()
"@
}
$launcherBody += @"

`$node = '$($NodeExe -replace "'","''")'
`$cli = '$($cli -replace "'","''")'
`$repo = '$($RepoRoot -replace "'","''")'
Set-Location -LiteralPath `$repo
& `$node `$cli run *>> '$($log -replace "'","''")'
exit `$LASTEXITCODE
"@

if ($PSCmdlet.ShouldProcess($launcher, 'Write launcher')) {
  Set-Content -LiteralPath $launcher -Value $launcherBody -Encoding UTF8
}

$arg = "-NoProfile -ExecutionPolicy Bypass -File `"$launcher`""
$action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument $arg -WorkingDirectory $RepoRoot
$trigger = New-ScheduledTaskTrigger -Daily -At $DailyAt
$settings = New-ScheduledTaskSettingsSet `
  -StartWhenAvailable `
  -DontStopIfGoingOnBatteries `
  -AllowStartIfOnBatteries `
  -ExecutionTimeLimit (New-TimeSpan -Hours 4) `
  -MultipleInstances IgnoreNew

$principalParams = @{
  LogonType = 'Interactive'
  RunLevel  = 'Limited'
}
if ($RunAsUser) {
  $principalParams.UserId = $RunAsUser
  $principalParams.LogonType = 'Password'
}
$principal = New-ScheduledTaskPrincipal @principalParams

Write-Host "TaskName=$TaskName"
Write-Host "DailyAt=$DailyAt"
Write-Host "MultipleInstances=IgnoreNew"
Write-Host "Cli=$cli"
Write-Host "Log=$log"
Write-Host "Lock=$lock"
Write-Host "Launcher=$launcher"
Write-Host "MSSQL_SERVER=$MssqlServer"
Write-Host "MSSQL_DATABASE=$MssqlDatabase"
if ($useTrusted) {
  Write-Host 'MSSQL_TRUSTED_CONNECTION=true'
} else {
  Write-Host "MSSQL_USER=$MssqlUser"
  Write-Host 'MSSQL_PASSWORD=(from file)'
}

if ($WhatIfPreference) {
  Write-Host "WhatIf: would Register-ScheduledTask $TaskName daily at $DailyAt MultipleInstances IgnoreNew"
  return
}

if ($PSCmdlet.ShouldProcess($TaskName, 'Register-ScheduledTask')) {
  Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings -Principal $principal -Force | Out-Null
  Write-Host "Registered $TaskName daily at $DailyAt"
}
