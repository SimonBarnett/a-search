'use strict';
const { describe, it } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ROOT = path.join(__dirname, '..');
const SKILL = path.join(ROOT, '.grok', 'skills', 'harvest-agent-skills', 'SKILL.md');
const NEEDLE = 'Harvest-lesson MRB: if PR body still says admin-merge when Actions QUEUED but tip bullet already cites FR #3948 --auto --squash, PASS the tip content (body drift ACCEPTABLE); reject only if tip still teaches --admin';
describe('MRB #2639 hostile admin-merge body-drift ACCEPTABLE harvest lesson', () => {
  it('SKILL.md contiguous body-drift lesson (UTF-8 no BOM)', () => {
    const raw = fs.readFileSync(SKILL);
    assert.equal(raw[0] === 0xef && raw[1] === 0xbb && raw[2] === 0xbf, false);
    assert.ok(raw.toString('utf8').includes(NEEDLE), 'missing contiguous lesson needle');
    assert.doesNotMatch(raw.toString('utf8'), /^<<<<<<<|^=======|^>>>>>>>/m);
  });
});
