'use strict';

/**
 * Ecwid products -> Parts staging (FR-246).
 * MerchantProductId = product id (string). One row per product (parent).
 */

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const DEFAULT_FIXTURE = path.join(
  __dirname,
  '..',
  'fixtures',
  'products-ok.json',
);

const REQUIRED_PARTS_FIELDS = [
  'Source',
  'FeedKey',
  'MerchantProductId',
  'Env',
  'Title',
];

function contentHashForPartsRow(row) {
  const payload = [
    row.Title,
    row.Description,
    row.Url,
    row.ImageUrl,
    row.Price,
    row.Currency,
    row.Stock,
  ]
    .map((v) => (v == null ? '' : String(v)))
    .join('\0');
  return crypto.createHash('sha256').update(payload, 'utf8').digest('hex');
}

function assertPartsRow(row) {
  for (const f of REQUIRED_PARTS_FIELDS) {
    if (row[f] == null || row[f] === '') {
      throw new Error(`assertPartsRow: missing ${f}`);
    }
  }
  return row;
}

/**
 * @param {string} shopDomain
 * @param {object} product
 */
function absoluteProductUrl(shopDomain, product) {
  if (product.url && /^https?:\/\//i.test(String(product.url))) {
    return String(product.url);
  }
  if (product.autogeneratedSlug) {
    const domain = String(shopDomain || '')
      .replace(/^https?:\/\//, '')
      .replace(/\/$/, '');
    if (domain) {
      return `https://${domain}/products/${product.autogeneratedSlug}`;
    }
  }
  const domain = String(shopDomain || '')
    .replace(/^https?:\/\//, '')
    .replace(/\/$/, '');
  return domain ? `https://${domain}/` : '';
}

function imageUrl(product) {
  if (product.imageUrl) return String(product.imageUrl);
  if (product.thumbnailUrl) return String(product.thumbnailUrl);
  const media = product.media && product.media.images;
  if (Array.isArray(media) && media[0]) {
    return String(media[0].imageOriginalUrl || media[0].image150pxUrl || '');
  }
  return null;
}

/**
 * @param {object} product
 * @param {{ source?: string, env: string, feedKey: string, shopDomain?: string, currency?: string }} meta
 */
function normalizeEcwidProduct(product, meta) {
  if (!meta || typeof meta !== 'object') {
    throw new Error('normalizeEcwidProduct: meta required');
  }
  const feedKey = String(meta.feedKey || '').trim();
  const env = String(meta.env || '').trim();
  if (!feedKey) throw new Error('normalizeEcwidProduct: meta.feedKey required');
  if (env !== 'live' && env !== 'sandbox') {
    throw new Error(
      `normalizeEcwidProduct: meta.env must be live|sandbox, got ${JSON.stringify(env)}`,
    );
  }
  const p = product || {};
  if (p.enabled === false) return null;
  const id = p.id != null ? String(p.id).trim() : '';
  const title = p.name != null ? String(p.name).trim() : '';
  if (!id || !title) return null;

  let price = null;
  if (
    p.defaultDisplayedPrice != null &&
    String(p.defaultDisplayedPrice).trim() !== ''
  ) {
    const n = Number(p.defaultDisplayedPrice);
    price = Number.isFinite(n) ? n : null;
  } else if (p.price != null && String(p.price).trim() !== '') {
    const n = Number(p.price);
    price = Number.isFinite(n) ? n : null;
  }

  const row = {
    Source: String(meta.source || 'ecwid'),
    FeedKey: feedKey,
    MerchantProductId: id,
    Env: env,
    Title: title,
    Description: p.description != null ? String(p.description) : null,
    Url: absoluteProductUrl(meta.shopDomain, p),
    ImageUrl: imageUrl(p),
    Price: price,
    Currency: meta.currency || 'GBP',
    Stock: p.quantity != null ? Number(p.quantity) : null,
  };
  row.ContentHash = contentHashForPartsRow(row);
  return assertPartsRow(row);
}

function normalizeEcwidCatalog(body, meta) {
  let items = [];
  if (Array.isArray(body)) items = body;
  else if (body && Array.isArray(body.items)) items = body.items;
  else if (body && Array.isArray(body.products)) items = body.products;
  else if (body && typeof body === 'object') items = [body];
  const out = [];
  for (const p of items) {
    const row = normalizeEcwidProduct(p, meta);
    if (row) out.push(row);
  }
  return out;
}

function loadFixtureProducts(fixturePath) {
  const raw = fs.readFileSync(fixturePath || DEFAULT_FIXTURE, 'utf8');
  const json = JSON.parse(raw);
  return Array.isArray(json.items) ? json.items : json.products || json;
}

module.exports = {
  REQUIRED_PARTS_FIELDS,
  contentHashForPartsRow,
  assertPartsRow,
  absoluteProductUrl,
  normalizeEcwidProduct,
  normalizeEcwidCatalog,
  loadFixtureProducts,
  DEFAULT_FIXTURE,
};
